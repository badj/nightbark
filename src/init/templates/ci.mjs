/**
 * CI for the generated project, both platforms.
 *
 * ⚠️ EVERY SCALAR IS QUOTED, and that is not fussiness. The first CI this repo generated for ITSELF
 * was invalid YAML because a step label contained a colon, and it was caught only by feeding the
 * output to a real parser. A scaffold shipping broken CI would be a bad first impression and a
 * confusing one, since the error appears in the user's repo rather than in the generator.
 */
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const STEPS = [
    { label: 'Install Playwright browsers', run: 'npx playwright install --with-deps chromium' },
    { label: 'Tests', run: 'npx playwright test' },
    // Soft on purpose: the scaffold ships one deliberately-vacuous test, so a hard failure here
    // would make every brand-new project red on its first push. Tighten once it is deleted.
    { label: 'nightbark audit (read-only)', run: 'npx -y github:badj/nightbark audit . --sarif nightbark.sarif --fail-on never', soft: true },
];

export const renderGithub = (name) => `# Generated by nightbark init. Safe to edit — this is yours now.
name: ${q(name)}

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

permissions:
  contents: read
  security-events: write   # lets the SARIF below annotate the pull-request diff

jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: '22'
      - name: ${q('Install dependencies')}
        run: ${q('npm ci || npm install')}
${STEPS.map((s) => `      - name: ${q(s.label)}\n        run: ${q(s.run)}${s.soft ? '\n        continue-on-error: true' : ''}`).join('\n')}
      - name: ${q('Annotate audit findings on the diff')}
        if: always()
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: ${q('nightbark.sarif')}
        continue-on-error: true
      - name: ${q('Keep the Playwright report')}
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: ${q('playwright-report')}
          path: ${q('playwright-report/')}
`;

export const renderAzure = (name) => `# Generated by nightbark init. Safe to edit — this is yours now.
# pipeline: ${name}
trigger:
  branches:
    include:
      - main

pr:
  branches:
    include:
      - main

pool:
  vmImage: ubuntu-latest

steps:
  - task: NodeTool@0
    displayName: ${q('Use Node 22')}
    inputs:
      versionSpec: '22'

  - script: ${q('npm ci || npm install')}
    displayName: ${q('Install dependencies')}

${STEPS.map((s) => `  - script: ${q(s.run)}\n    displayName: ${q(s.label)}${s.soft ? '\n    continueOnError: true' : ''}`).join('\n')}

  - task: PublishPipelineArtifact@1
    displayName: ${q('Keep the Playwright report')}
    condition: always()
    inputs:
      targetPath: ${q('playwright-report')}
      artifact: ${q('playwright-report')}
`;
