import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pipeline } from '../ci/pipeline.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const GH = '.github/workflows/nightbark.yml';
const ADO = 'azure-pipelines.yml';

/**
 * ⚠️ THE FIRST GENERATED WORKFLOW WAS INVALID YAML and would have shipped broken CI.
 *
 * A step label contained a colon — `ADR-0001: no client-identifying content` — and an unquoted
 * scalar with a colon in it is a parse error. It was caught only by feeding the output to a real
 * YAML parser, which is not available here as a dependency.
 *
 * So these tests check the CLASS of bug rather than re-parsing: every value emitted into a scalar
 * position must be quoted. That catches colons, leading `*`, embedded `"` and `#` — all of which
 * break a bare scalar — without adding a parser to a zero-dependency tool.
 */

const SCALAR_KEYS = ['name', 'run', 'script', 'displayName'];

for (const file of [GH, ADO]) {
    test(`${file}: every emitted scalar is quoted, so a colon in a label cannot break it`, () => {
        for (const line of read(file).split('\n')) {
            const m = line.match(/^\s*-?\s*(name|run|script|displayName):\s*(.+)$/);
            if (!m) continue;
            const value = m[2].trim();
            // `uses:` style refs and a bare `name:` on the workflow itself are not step scalars;
            // every one this matches is a label or a command, and must be quoted.
            assert.ok(
                value.startsWith("'") || value.startsWith('"'),
                `unquoted ${m[1]} in ${file}: ${value} — a colon or leading * here is a parse error`,
            );
        }
    });

    test(`${file}: carries the generated-file banner so nobody hand-edits it`, () => {
        const t = read(file);
        assert.match(t, /GENERATED by scripts\/gen-ci\.mjs/);
        assert.match(t, /DO NOT EDIT BY HAND/);
    });

    test(`${file}: runs every step the definition declares`, () => {
        const t = read(file);
        for (const s of pipeline.steps) {
            assert.ok(t.includes(s.run), `${file} is missing the step: ${s.run}`);
        }
    });
}

test('a step marked failsBuild:false is allowed to continue, on both platforms', () => {
    const soft = pipeline.steps.filter((s) => !s.failsBuild);
    assert.ok(soft.length > 0, 'the fixture self-audit should be soft — fixtures contain deliberate defects');
    assert.match(read(GH), /continue-on-error: true/);
    assert.match(read(ADO), /continueOnError: true/);
});

test('⚠️ the selftest step comes FIRST — gates are proven before anything is audited with them', () => {
    // Order is load-bearing, not cosmetic. A gate that cannot fail reports compliance it never
    // verified, so auditing with unproven gates would produce a green nobody should trust.
    assert.equal(pipeline.steps[0].id, 'selftest');
    const gh = read(GH);
    assert.ok(gh.indexOf('selftest') < gh.indexOf('audit fixtures'));
});

test('GitHub gets the SARIF upload and the permission it needs', () => {
    const t = read(GH);
    // Without security-events:write the upload silently fails and the annotations never appear —
    // the finding would be produced and then quietly dropped.
    assert.match(t, /security-events:\s*write/);
    assert.match(t, /upload-sarif@v\d/);
});

test('both platforms keep the SARIF as an artifact even when a step failed', () => {
    assert.match(read(GH), /if: always\(\)/);
    assert.match(read(ADO), /condition: always\(\)/);
});
